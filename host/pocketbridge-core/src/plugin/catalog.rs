/// Find a manifest from the default catalog by plugin id or adapter id.
pub fn find_catalog_plugin(query: &str) -> Option<PluginManifest> {
    default_catalog()
        .into_iter()
        .find(|m| m.id == query || m.adapter_id == query)
}
